import {StrictMode} from 'react';
import {createRoot} from 'react-dom/client';
import App from './App.tsx';
import { ErrorBoundary } from './components/ErrorBoundary.tsx';
import { checkAndApplyVersionUpdate } from './utils/versionControl.ts';
import './index.css';

// Ejecutar verificación y control de caché/versiones al iniciar la aplicación
checkAndApplyVersionUpdate();

// Registro del Service Worker Oficial para PWA y descarga de la app con su logo
if (typeof window !== 'undefined' && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch((err) => {
      console.warn('Service worker registration non-fatal:', err);
    });
  });
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <ErrorBoundary>
      <App />
    </ErrorBoundary>
  </StrictMode>,
);

